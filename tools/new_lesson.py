"""new_lesson.py: scaffold a lesson folder.

usage:
  python tools/new_lesson.py <key> [--bare]                 a lesson from curriculum.md, by its permanent key
  python tools/new_lesson.py 00.02 "The map of everything" [--module Orientation] [--poc] [--bare] [--slug S]
                                                            the old form, for proofs of concept and tests

The key form (every new lesson since 2026-10-12) reads the id, title and module from curriculum.md
(tools/course.py) and creates lessons/<key>/ (no number in the folder or the URL, so moving the lesson never
renames it) with:
  index.html     from engine/lesson-template.html; loads engine/course.js + engine/map.js
  scenes/02.js   the standard map scene: SCENE('02', (t, S) => K.map.intro(t, S));
  script.md      section 02 `## 02 — Where this sits on the map [map]`, its narration generated by
                 tools/course.py sync (re-run sync after editing curriculum.md; never edit that text by hand)
  lesson.js      key / id / title / short / module (skipped with --bare: the production workflow writes it)
  course-sync.json  what the map looked like when the lesson was scaffolded (tools/course.py sync keeps it)

Re-running only refreshes index.html (and the [map] section, through sync). Scaffolding runs course.py sync over
every built lesson; its report (what it rewrote, what needs narration or a re-render) is printed on stderr, and
stdout is only the new folder's path.

Testing the key form on a fixture: --curriculum <fixture.md> --lessons <dir> --course-js <file> [--registry <file>].
"""
import argparse
import datetime
import html
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from common import ENGINE, LESSONS, MAPJS_NEW, mapjs  # noqa: E402

SCRIPT = """# {id} — {title}
<!-- lead=1.6 gap=0.8 tail=3 -->

> Conceptual lesson, 3-6 minutes, ~450-750 spoken words. Write for the ear:
> spell things the way they are said ("dot P Y", "V S Code"); on-screen text carries the literal form.
> Put [[cue-name]] exactly where an animation beat should land.

## 01 — The point
State the conclusion first. [[hook]]

## 02 — Where it lives on the map
...
"""

# key form: section 01 is a placeholder the workflow replaces; section 02 is the standard map section
SCRIPT_KEY = """# {id} — {title}
<!-- lead=1.6 gap=0.8 tail=3 -->

> Section 02 is the standard map section: tools/course.py sync writes its narration from curriculum.md and its
> scene is scenes/02.js. Keep its heading and the map:begin / map:end markers; write every other section.

## 01 — The point
In this lesson you'll learn ... [[point]]

{map_section}"""

LESSON_JS = """/* {id} — {title}
   Scenes are keyed by the ## NN sections of script.md. Each scene gets (t, S):
   t = seconds since its narration section began (negative during the lead-in),
   S.cue('name', fallback) = local time of [[name]] in the script, S.dur = narration length,
   S.out = when the scene hands over. Draw everything from t alone. */
LESSON({{{key_line}
  id: '{id}',
  title: '{title}',
  short: '{title}',
  module: '{module}',{poc}
  summary: '',
  keep: [
    // ['Bold lead that carries the idea alone.', 'Supporting sentence.'],
  ],
  images: {{}},
  draft: {{ '01': 10, '02': 12 }},
  noBadge: ['01'],
  scenes: {{
    '01': (t, S) => {{
      K.bg();
      K.title('{title}', K.W / 2, 560, {{ align: 'center', size: 96, alpha: K.io(t, 0, 0.8) }});
    }},{scene02}
  }},
}});
"""
SCENE02_OLD = """
    '02': (t, S) => {{
      K.bg();
      K.map.draw(t, {{ t0: 0, pin: '{mod}' }});
    }},"""


def page(slug, lid, title, summary='', mapjs_tag=MAPJS_NEW):
    t = (ENGINE / 'lesson-template.html').read_text(encoding='utf-8')
    return (t.replace('{{SLUG}}', slug).replace('{{ID}}', html.escape(lid)).replace('{{TITLE}}', html.escape(title))
             .replace('{{SUMMARY}}', html.escape(summary)).replace('{{DATE}}', datetime.date.today().isoformat())
             .replace('{{PREV}}', '').replace('{{NEXT}}', '').replace('{{MAPJS}}', mapjs_tag))


def js_str(s):
    return s.replace('\\', '\\\\').replace("'", "\\'")


def from_key(a):
    import contextlib
    import course  # noqa: E402
    cur = pathlib.Path(a.curriculum).resolve() if a.curriculum else course.CURRICULUM
    fixture = cur != course.CURRICULUM.resolve()
    if fixture and (not a.course_js or not a.lessons):
        raise SystemExit('with --curriculum <fixture>, pass --course-js <file> and --lessons <dir> too, so a test never '
                         'writes engine/course.js or the real lessons/')
    lessons_dir = pathlib.Path(a.lessons).resolve() if a.lessons else LESSONS
    c = course.load(cur, lessons_dir=lessons_dir, registry=a.registry)
    les = c.lesson(a.ref)
    if not les:
        raise SystemExit(f'{a.ref!r} is not a lesson key or id in {course.rel(c.path)}')
    if c.format != 'new':
        raise SystemExit('curriculum.md is in the old format (no lesson keys): use the old form, '
                         'python tools/new_lesson.py <id> "<title>" --module <name>')
    key = les['key']
    mod = c.modules[les['module']]
    d = lessons_dir / key
    fresh = not d.exists()
    d.mkdir(parents=True, exist_ok=True)
    (d / 'assets').mkdir(exist_ok=True)
    (d / 'scenes').mkdir(exist_ok=True)
    if a.bare:
        (d / 'drafts').mkdir(exist_ok=True)
    (d / 'index.html').write_text(page(key, les['id'], les['title']), encoding='utf-8', newline='\n')
    if not (d / 'scenes' / '02.js').exists():
        (d / 'scenes' / '02.js').write_text(course.MAP_SCENE, encoding='utf-8', newline='\n')
    if not (d / 'script.md').exists():
        sec = course.MAP_SECTION.format(block=course.map_block(c, les))
        (d / 'script.md').write_text(SCRIPT_KEY.format(id=les['id'], title=les['title'], map_section=sec), encoding='utf-8', newline='\n')
    if not a.bare and not (d / 'lesson.js').exists():
        (d / 'lesson.js').write_text(LESSON_JS.format(key_line=f"\n  key: '{key}',", id=les['id'], title=js_str(les['title']),
                                                     module=js_str(mod['full']), poc='', scene02=''), encoding='utf-8', newline='\n')
    # sync writes course.js (this lesson is now built: it gets its slug), the lesson's course-sync.json, and refreshes
    # every other built lesson too: its report (what it rewrote, what now needs narration or a re-render) goes to
    # stderr, so a curriculum change made since the last sync never goes unnoticed; stdout stays the folder path
    with contextlib.redirect_stdout(sys.stderr):
        course.sync(c, a.course_js or course.COURSE_JS, quiet=False)
    if fresh:
        print(f"scaffolded {les['id']} {les['title']} (module {mod['n']} {mod['name']}, {c.region(les['district'])['name']})", file=sys.stderr)
    print(d)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('ref', help='a lesson key from curriculum.md, or (old form) an id like 00.02')
    ap.add_argument('title', nargs='?', help='old form only: the title')
    ap.add_argument('--module', default='')
    ap.add_argument('--summary', default='')
    ap.add_argument('--poc', action='store_true')
    ap.add_argument('--slug')
    ap.add_argument('--bare', action='store_true', help='for the workflow: make drafts/ and scenes/, no skeleton lesson.js')
    ap.add_argument('--curriculum', help='key form, testing: read this curriculum.md (needs --course-js and --lessons)')
    ap.add_argument('--lessons', help='key form, testing: scaffold into this folder instead of lessons/')
    ap.add_argument('--course-js', help='key form, testing: write the course data here instead of engine/course.js')
    ap.add_argument('--registry', help='key form, testing: read this course.json')
    a = ap.parse_args()
    if a.title is None:
        return from_key(a)
    # the old form: <id> "<title>" (proofs of concept, tests); the slug carries the id
    slug = a.slug or (a.ref.replace('.', '-') + '-' + re.sub(r'[^a-z0-9]+', '-', a.title.lower()).strip('-'))
    if a.poc and not slug.startswith('poc-'):
        slug = 'poc-' + slug
    d = LESSONS / slug
    d.mkdir(parents=True, exist_ok=True)
    (d / 'assets').mkdir(exist_ok=True)
    (d / 'index.html').write_text(page(slug, a.ref, a.title, a.summary, mapjs(slug)), encoding='utf-8', newline='\n')
    if a.bare:
        (d / 'drafts').mkdir(exist_ok=True)
        (d / 'scenes').mkdir(exist_ok=True)
    if a.bare or (d / 'drafts').exists() or (d / 'scenes').exists() and any((d / 'scenes').iterdir()):
        print(d)  # lesson already in production: only the page was refreshed
        return
    if not (d / 'script.md').exists():
        (d / 'script.md').write_text(SCRIPT.format(id=a.ref, title=a.title), encoding='utf-8')
    if not (d / 'lesson.js').exists():
        (d / 'lesson.js').write_text(LESSON_JS.format(key_line='', id=a.ref, title=js_str(a.title), module=a.module,
                                                       poc="\n  poc: true," if a.poc else '',
                                                       scene02=SCENE02_OLD.format(mod=a.ref.split('.')[0])), encoding='utf-8')
    print(d)


if __name__ == '__main__':
    main()
